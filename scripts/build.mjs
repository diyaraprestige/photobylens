// Builds Photobylens for one target:  node scripts/build.mjs <pages|app|ext>
//   pages -> dist/pages      (GitHub Pages website)
//   app   -> www             (Android app via Capacitor)
//   ext   -> dist/extension  (Chrome / Edge extension)
// Settings come from env: PBL_API_BASE (payment API address), GITHUB_REPOSITORY.
import { cpSync, mkdirSync, rmSync, writeFileSync, readFileSync } from 'node:fs';
import path from 'node:path';

const target = process.argv[2];
const OUT = { pages: 'dist/pages', app: 'www', ext: 'dist/extension' }[target];
if (!OUT) { console.error('Usage: node scripts/build.mjs <pages|app|ext>'); process.exit(1); }

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
let apiBase = (process.env.PBL_API_BASE || '').trim();
if (apiBase && !apiBase.endsWith('/')) apiBase += '/';
const repo = process.env.GITHUB_REPOSITORY || 'diyaraprestige/photobylens';

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });
for (const f of ['index.html', 'paid.html', 'manifest.webmanifest']) cpSync(f, path.join(OUT, f));
cpSync('assets', path.join(OUT, 'assets'), { recursive: true });
writeFileSync(path.join(OUT, 'assets/config.js'),
  `/* Generated by scripts/build.mjs for "${target}" (v${pkg.version}). */\nwindow.PBL_CONFIG = ${JSON.stringify({ apiBase, repo, target, version: pkg.version }, null, 2)};\n`);

if (target === 'pages') writeFileSync(path.join(OUT, '.nojekyll'), '');
if (target === 'ext') {
  const m = JSON.parse(readFileSync('extension/manifest.json', 'utf8'));
  m.version = pkg.version.replace(/[^0-9.]/g, '') || '1.0.0';
  if (apiBase) m.host_permissions.push(new URL(apiBase).origin + '/*');
  writeFileSync(path.join(OUT, 'manifest.json'), JSON.stringify(m, null, 2));
  cpSync('extension/background.js', path.join(OUT, 'background.js'));
  rmSync(path.join(OUT, 'manifest.webmanifest'));
}
console.log(`Built ${target} -> ${OUT} (api: ${apiBase || 'same site'})`);
